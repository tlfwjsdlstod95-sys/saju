// 엔진 판정 버전.
//
// 왜 필요한가
//   강약(dayMasterStrength)·용신(computeYongsin)·격국 판정 로직이나 임계값을 바꾸면
//   "같은 사람인데 어제와 다른 명식 해석"이 나온다. 그런데 우리는
//     ① AI 풀이를 Redis 에 60일 캐시하고
//     ② 구매한 리포트 원문을 saju_reports 에 영구 보관한다.
//   버전을 안 남기면 **옛 판정으로 쓰인 글이 새 판정 화면 옆에 그대로 붙는다**.
//   (화면엔 '중화'라고 뜨는데 본문은 '신강한 당신은…' 으로 시작하는 사고)
//
// 규칙
//   - 강약·용신·격국·조후 중 **판정 결과가 달라질 수 있는 변경**을 하면 반드시 올린다.
//   - 문구·설명문(desc)만 고친 경우는 올리지 않아도 된다(같은 판정이므로).
//   - 올리면 Redis 캐시가 자동으로 미스가 나 새로 생성되고, 보관된 옛 리포트는
//     meta.engine 으로 구분돼 "이전 판정 기준" 배지를 붙일 수 있다.
//
// 이력
//   1 — 최초. 득령/득지/득세 이진 판정 + 억부 3분기(신약→인성/신강→식상/중화→재성)
//       + 조후우선>병약>통관>억부 우선순위. (2026-08 일간 자기 자신 제외 수정 포함)
//   2 — 조후용신 '자격' 규칙 도입(2026-09-01). 조후 오행이 원국에서 무근이거나 천간합으로
//       묶이면 조후우선을 걸지 않고 억부로 내려간다. 적천수천미가 규준화된 조후용신법을
//       명시적으로 부정한 골든 케이스 5건에서 나온 규칙.
//       영향: 조후우선 19.0%→13.8%, 억부 69.1%→73.8%. 강약·격국·조후분류는 불변.
//       골든 용신 일치율 10%→30%.
//   3 — 격국 취용 '정기 우선' 교정(2026-09-01). 구버전은 월지 정기가 천간에 투출하지
//       않으면 중기·여기까지 내려가 투출한 글자로 격을 바꿨다. 자평진전 「論用神」의
//       用神專尋月令 원칙과 어긋난다(본기가 격이고, 여기·중기는 변화 사유일 뿐).
//       자평진전 원문 명식 5건(JPJ-013/014/018/019/022)이 전부 이 경로로 오판했다.
//       영향: 골든 격국 80.0%(20/25) → 100.0%(25/25).
//             분포는 건록격 5.67%→10.11%(정기=일간일 때 건너뛰던 버그도 같이 해소),
//             양인격 10.31%→9.75%, 나머지 격 -0.1~-1.2%p. 강약·용신·조후는 불변.
//   4 — 억부용신 중화 구간 교정(2026-09-01). '중화→재성'을 '중화→식상'으로 바꿨다.
//       적천수천미 원전에서 임철초가 고른 십신을 강약 구간별로 집계하니 중화 4건 중
//       재성이 0건이었다(식상 3, 비겁 1). 근거 없는 규칙이었다.
//       영향: 골든 용신 50.0%(9/18) → 66.7%(12/18). 강약·격국·조후 불변.
//             분포 이동 최대 1.9%p(용신오행 금 +1.9 / 수 -1.55). 불변식 26 PASS.
//   5 — 신살 길흉 반전(용신 종속) 도입(2026-09-01). 신살·12신살이 앉은 글자가 용신·희신이면
//       tone 을 한 단계 올리고(positive), 기신·구신이면 한 단계 내린다(negative). 한신이거나
//       길·흉이 섞이면 반전하지 않는다. desc 에 근거 문장이 붙어 AI 프롬프트·리포트 내용이
//       달라지므로 버전을 올린다. 강약·용신·격국·조후 판정 자체는 불변(baseline 이동 0 확인).

//   6 — 억부 '후보 평가·소거' 구조 도입(2026-09-02). 가장 큰 변경이다.
//       구: 신약→인성 / 그 외→식상  (고정 매핑 — 비겁·재성·관살에 도달 불가)
//       신: 강약 방향의 후보(신약=인성·비겁 / 그 외=식상·재성·관살)를 만들고
//           ①원국 실재 ②천간 투출·지지 뿌리·합국(삼합 2자 포함) ③천간합으로 묶임
//           ④극하는 세력에 빼앗김 ⑤무엇 때문에 약한가(식상과다→인성 / 관살과다→비겁)
//           로 채점해 최고점을 채택한다. 임철초가 후보를 지워 나가는 방식을 그대로 옮긴 것:
//           「用官則被庚金合壞, 用食則官又不從化 … 無奈何而用財」(JCS-034)
//       함께 바뀐 것:
//         · 병약의 '약' — 병이 인성이면 극(財破印)이 아니라 설(洩身)을 먼저 본다(土多金埋 淘洗, JCS-010)
//         · 종왕격 — 강약 임계(0.90)만이 아니라 '지지가 일간 오행으로 국을 이루고
//           극하는 세력이 뿌리 없이 뜬 경우'도 從으로 본다(從火, JCS-006)
//         · 조후우선 — 일간이 극도로 약하면(≤0.15) 계절보다 부신이 먼저다(冬金, JCS-003/007)
//       영향: 골든 용신 66.7%(12/18) → **94.4%(17/18)**. 강약·격국·조후 지표는 불변.
//             분포 이동 최대 3.26%p(조후우선 13.8→10.5 / 억부 73.8→76.5). 불변식 26 PASS.
//       ⚠️ 남은 1건 JCS-007 은 강약 오판(중화/문헌 신약) + 濕土·凍土가 生金 못한다는 논리 미구현.

//   7 — 상관격을 '한 갈래'가 아니라 '다섯 갈래'로 본다(2026-09-02).
//       계기: 원전 傷官편(p.77~92)을 통째로 읽어 골든 18건을 캤더니 용신 재현율이
//         94.4%(튜닝 18건) → 63.6%(44건)로 무너졌다. 오답의 대부분이 이 한 챕터였고,
//         원인이 하나였다 — **문헌은 財나 官을 쓰는데 엔진은 늘 식상을 골랐다.**
//       근거는 추정이 아니라 임철초가 직접 써 놓은 표다(傷官 p.78 任氏曰):
//         「有傷官用印, 傷官用財, 傷官用刦, 傷官用傷官, 傷官用官, 其間作用種種不同, 不可執一而論也.
//           若傷官用財者, 日主旺, 傷官亦旺, 宜用財, 有比刦而可見官, 無比刦有印綬, 不可見官.
//           日主弱, 傷官旺, 宜用印, 可見官而不可見財.
//           日主弱, 傷官旺, 無印綬, 宜用比刦, 喜見刦印, 忌見財官.
//           日主旺, 無財官, 宜用傷官, 喜見財傷, 忌見官印.
//           日主旺, 比刦多, 財星衰, 傷官輕, 宜用官, 喜見財官, 忌見傷印.」
//       옮긴 규칙(모두 v6 후보 소거 위에 얹는 **가점**이다 — 무근·합거로 소거된 후보는 살아나지 않는다):
//         · 日主旺 + 傷官旺 + 財 있음 → 재성 우선(傷官用財). 이때 일간이 財를 剋하는 것은
//           흠이 아니라 用의 조건이므로(能任財) 재성에 걸리던 '극당함' 감점을 면제한다.
//         · 日主旺 + 比刦多 + 財衰 + 傷官輕 → 관살 우선(傷官用官)
//         · 日主弱 + 無印綬 + 財 둘 이상 → 비겁 우선(傷官用刦). 用刦은 刦財라 나눌 財가 있어야 한다.
//         · 日主弱인데 印이 식상보다 무거우면 → 식상을 후보에 추가(母慈滅子, 「必以卯木爲用」JCS-050·051).
//           반대로 식상이 더 무거우면 종전대로 印으로 制傷한다(「必須用己土之印」JCS-038).
//       함께 고친 것 — 조후 자격의 '뿌리' 정의:
//         지장간에만 숨어 있으면 천간에 같은 오행이 투출했을 때만 뿌리로 친다.
//         근거 「寒甚而暖無氣, 反以無暖爲美」(JCS-043). 이걸로 겨울 金水 명식에서
//         원전이 안 쓰는 조후 火를 억지로 올리던 3건이 정리됐다(JCS-059·068·070).
//       영향: 골든 용신 63.6%(28/44) → **77.3%(34/44)**, 그중 튜닝에 안 쓴 신규 표본만 보면
//             42.3%(11/26) → **65.4%(17/26)**. 용신 반례 3/4 → **4/4**.
//             강약·격국·조후 지표 불변(88% / 100% / 100%). 불변식 26 PASS.
//             분포 이동: 조후우선 10.5→8.1 / 억부 76.5→78.4, 종격·격국·강약 분포는 그대로.
//       ⚠️ 남은 오답 10건의 성격: 종격 과발동 2(JCS-053·060) · 억부 순위 5 · 기존 2 · 통관 1.
//         다음 후보는 從 문턱 재보정(과발동·미발동이 양쪽으로 난다)이다.

