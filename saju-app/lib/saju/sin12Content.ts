export const SIN12_SLUGS = SIN12_ORDER as readonly Sin12[];

export function findSin12(slug: string): Sin12 | null {
  const s = decodeURIComponent(slug);
  return (SIN12_ORDER as readonly string[]).includes(s) ? (s as Sin12) : null;
}

/** 이 신살이 어느 띠(년지)에게 어느 지지로 붙는지 — 12지지 전체 대응표 */
export function sin12ByBase(name: Sin12): { base: string; animal: string; ji: string }[] {
  const out: { base: string; animal: string; ji: string }[] = [];
  for (let b = 0; b < 12; b++) {
    const map = sin12Map(b);
    const ji = map.findIndex((n) => n === name);
    out.push({
      base: `${JIJI[b]}(${JIJI_HANJA[b]})`,
      animal: JIJI_ANIMAL[b],
      ji: `${JIJI[ji]}(${JIJI_HANJA[ji]})`,
    });
  }
  return out;
}
